def _normalize_value(value):
    return (value or "").strip().lower()


def filtered_sites(params):
    conservation = _normalize_value(params.get("conservation"))
    state = params.get("state", "").strip()
    query = _normalize_value(params.get("q"))

    sites = SITES

    if conservation:
        sites = [site for site in sites if site["conservation"] == conservation]

    if state:
        sites = [site for site in sites if site["state"] == state]

    if query:
        sites = [
            site
            for site in sites
            if query in site["name"].lower()
            or query in site["municipality"].lower()
            or query in site["summary"].lower()
        ]

    return sites


